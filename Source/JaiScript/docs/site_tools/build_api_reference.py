#!/usr/bin/env python3
"""Generate the full API page and checker arities from reference/api-catalog.json.

--check compares generated artifacts without changing them. Updating a signature
updates searchable docs and load-time method arities together; runtime guards
remain in the implementations. This tool invokes no compiler or script runner.
"""
import argparse
import hashlib
import html
import json
import pathlib
import re
import sys

SITE = pathlib.Path(__file__).resolve().parent.parent / "site"
PROJECT = SITE.parents[1]
CATALOG = SITE / 'reference/api-catalog.json'
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from mark_runnable import marked  # noqa: E402

def escape(value):
	return html.escape(str(value), quote=True)

def parameter_list(signature):
	start = signature.index('(') + 1
	depth = 1
	quote = None
	parts, begin = [], start
	for i in range(start, len(signature)):
		c = signature[i]
		if quote:
			if c == quote and signature[i - 1] != '\\': quote = None
			continue
		if c in ['"', "'"]:
			quote = c
		elif c == '(':
			depth += 1
		elif c == ')':
			depth -= 1
			if depth == 0:
				if signature[begin:i].strip(): parts.append(signature[begin:i].strip())
				return parts
		elif c == ',' and depth == 1:
			parts.append(signature[begin:i].strip())
			begin = i + 1
	raise ValueError('Unbalanced signature: ' + signature)

def arity(signature):
	params = parameter_list(signature)
	minimum = sum('=' not in p and '...' not in p for p in params)
	maximum = 255 if any('...' in p for p in params) else len(params)
	return minimum, maximum

# the result kinds the checker reads: a signature's result when it is one scalar type, the receiver's text type or the element type
RESULTS = {'int': 'int_result', 'float': 'float_result', 'bool': 'bool_result', 'string': 'string_result', 'char': 'char_result',
	'Self': 'self_text', 'T': 'element'}

def result_kind(signature):
	return RESULTS.get(signature.rsplit('->', 1)[1].strip(), 'open') if '->' in signature else 'open'

# the argument shapes the checker reads: a parameter's catalog type as the set of shapes it takes (number, text, array, map,
# function, math value); a type the table does not name takes anything
SHAPES = {'number': 1, 'int': 1, 'float': 1, 'text': 2, 'string': 2, 'utf8_string': 2, 'char': 2, 'Self': 2,
	'vector': 32, 'vector2': 32, 'vector3': 32, 'matching_vector': 32, 'same_dimension_vector': 32, 'color': 32, 'math::color': 32}
ANY_SHAPE = 255

def shape_mask(type_text):
	mask = 0
	for alternative in type_text.split(' or '):
		alternative = alternative.strip()
		if alternative.startswith('array<'): shape = 4
		elif alternative.startswith('map<'): shape = 8
		elif alternative.startswith('function'): shape = 16
		else: shape = SHAPES.get(alternative, ANY_SHAPE)
		mask |= shape
	return mask

def parameter_masks(signature):
	masks = []
	for parameter in parameter_list(signature):
		if ':' not in parameter:
			masks.append(ANY_SHAPE)
			continue
		type_text = parameter.split(':', 1)[1]
		depth = 0
		for i, c in enumerate(type_text):   # the default follows the type's own text (a callback's -> result is part of the type)
			if c in '(<[': depth += 1
			elif c in ')>]': depth -= 1
			elif c == '=' and depth == 0 and type_text[i - 1] == ' ':
				type_text = type_text[:i]
				break
		masks.append(shape_mask(type_text.replace('...', '').strip()))
	return masks

SHAPE_SLOTS = 6

def shape_row(masks):
	masks = (masks + [masks[-1] if masks else ANY_SHAPE] * SHAPE_SLOTS)[:SHAPE_SLOTS] if masks else [ANY_SHAPE] * SHAPE_SLOTS
	return '{' + ', '.join(str(m) for m in masks) + '}'

def generated_header(entries):
	receivers = {'array<T>': 0, 'map<K,V>': 1, 'string': 2, 'utf8_string': 3}
	rows = {}
	results = {}
	shapes = {}
	functions = []
	for entry in entries:
		if entry['form'] == 'function' and entry['owner'] == 'math':
			minimum, maximum = arity(entry['signature'])
			functions.append((entry['name'], minimum, maximum, parameter_masks(entry['signature'])))
	for entry in entries:
		if entry['form'] != 'method' or entry['owner'] not in receivers: continue
		key = receivers[entry['owner']], entry['name']
		bounds = arity(entry['signature'])
		if key in rows:
			assert rows[key] == bounds, ('Conflicting method arity', key)
		rows[key] = bounds
		kind = result_kind(entry['signature'])
		results[key] = kind if results.get(key, kind) == kind else 'open'
		masks = parameter_masks(entry['signature'])
		masks = (masks + [masks[-1] if bounds[1] == 255 and masks else ANY_SHAPE] * SHAPE_SLOTS)[:SHAPE_SLOTS]
		shapes[key] = [a | b for a, b in zip(shapes.get(key, [0] * SHAPE_SLOTS), masks)]
	lines = ['#pragma once', '', '// Generated by docs/site_tools/build_api_reference.py; edit api-catalog.json.',
		'#include <array>', '#include <cstddef>', '#include <cstdint>', '#include <string_view>', '', 'namespace jai::detail {',
		"\t// result: what the method returns when the catalog states one type (self_text: the receiver's text type; element: the array's T)",
		'\tenum class BuiltinResult : uint8_t { open, int_result, float_result, bool_result, string_result, char_result, self_text, element };',
		'\t// shapes: per argument, the shapes the catalog says it takes (a past-the-end argument reads the last slot); every bit set takes anything',
		'\tenum BuiltinShape : uint8_t { shape_number = 1, shape_text = 2, shape_array = 4, shape_map = 8, shape_function = 16, shape_math = 32, shape_any = 255 };',
		f'\tinline constexpr size_t BUILTIN_SHAPE_SLOTS = {SHAPE_SLOTS};',
		'\tstruct BuiltinArity {', '\t\tuint8_t receiver;', '\t\tstd::string_view name;', '\t\tuint8_t minimum;', '\t\tuint8_t maximum;', '\t\tBuiltinResult result;',
		'\t\tuint8_t shapes[BUILTIN_SHAPE_SLOTS];', '\t};', '',
		f'\tinline constexpr std::array<BuiltinArity, {len(rows)}> BUILTIN_ARITIES{{{{']
	for (receiver, name), (minimum, maximum) in sorted(rows.items()):
		lines.append(f'\t\t{{{receiver}, "{name}", {minimum}, {maximum}, BuiltinResult::{results[(receiver, name)]}, {shape_row(shapes[(receiver, name)])}}},')
	lines += ['\t}};', '', '\tinline const BuiltinArity* findBuiltinArity(uint8_t a_receiver, std::string_view a_name) {',
		'\t\tfor (const auto& entry : BUILTIN_ARITIES) {',
		'\t\t\tif (entry.receiver == a_receiver && entry.name == a_name) { return &entry; }',
		'\t\t}', '\t\treturn nullptr;', '\t}', '']
	lines += ['\t// math:: functions by signature: a call checks its arguments against the signatures whose counts take it',
		'\tstruct BuiltinFunctionShape {', '\t\tstd::string_view name;', '\t\tuint8_t minimum;', '\t\tuint8_t maximum;', '\t\tuint8_t shapes[BUILTIN_SHAPE_SLOTS];', '\t};', '',
		f'\tinline constexpr std::array<BuiltinFunctionShape, {len(functions)}> MATH_FUNCTION_SHAPES{{{{']
	for name, minimum, maximum, masks in sorted(functions):
		lines.append(f'\t\t{{"{name}", {minimum}, {maximum}, {shape_row(masks)}}},')
	lines += ['\t}};', '']
	effects = receiver_effects(entries)
	lines += ["\t// What a builtin method does to its receiver, by name over every builtin receiver (the catalog's effect): one that",
		'\t// mutates any receiver writes; one that hands the elements to a callback reads unless the callback writes them',
		'\tenum class BuiltinReceiverEffect : uint8_t { reads, element_callback, writes };',
		'\tstruct BuiltinEffect {', '\t\tstd::string_view name;', '\t\tBuiltinReceiverEffect effect;', '\t};', '',
		f'\tinline constexpr std::array<BuiltinEffect, {len(effects)}> BUILTIN_RECEIVER_EFFECTS{{{{']
	for name, effect in sorted(effects.items()):
		lines.append(f'\t\t{{"{name}", BuiltinReceiverEffect::{effect}}},')
	lines += ['\t}};', '', '\tconstexpr const BuiltinEffect* findBuiltinEffect(std::string_view a_name) {',
		'\t\tfor (const auto& entry : BUILTIN_RECEIVER_EFFECTS) {',
		'\t\t\tif (entry.name == a_name) { return &entry; }',
		'\t\t}', '\t\treturn nullptr;', '\t}', '}', '']
	return '\n'.join(lines)

def receiver_effects(entries):
	receivers = {'array<T>', 'map<K,V>', 'string', 'utf8_string', 'shared_ptr<T>', 'weak_ptr<T>'}
	rank = {'reads': 0, 'element_callback': 1, 'writes': 2}
	result = {}
	for entry in entries:
		if entry['form'] != 'method' or entry['owner'] not in receivers: continue
		words = set(re.split(r'[,;]\s*', entry['effect']))
		if 'mutate' in words: effect = 'writes'
		elif 'callback' in words: effect = 'element_callback'
		elif words <= {'observe', 'copy'}: effect = 'reads'
		else: raise ValueError('No receiver effect for ' + entry['owner'] + '.' + entry['name'] + ': ' + entry['effect'])
		if entry['name'] not in result or rank[effect] > rank[result[entry['name']]]: result[entry['name']] = effect
	return result

def page(data):
	entries = sorted(data['entries'], key=lambda e: (e['owner'], e['form'], e['name'], e['signature'], e['provider']))
	parts = ['<article class="chapter"><h1 id="full-api">Full API signatures</h1>',
		'<p>The complete callable reference for core builtins, standard-library registrations, and the standalone runner. Each entry shows arguments, defaults, result, effects, and availability. Host applications may register additional APIs.</p>',
		'<p><a href="index.html">Reference overview</a> &middot; <a href="api-catalog.json" download>Machine-readable catalog</a></p>',
		'<h2 id="reading-signatures">Reading signatures</h2>',
		'<p>These signatures use documentation notation, rather than declaration syntax: <code>name(argument: type = default) -&gt; result</code>. <code>T</code>, <code>K</code>, <code>V</code>, and <code>R</code> stand for element, key, value, and callback-result types. <code>number</code> means int or float, <code>text</code> means string or utf8_string, and <code>Self</code> means the receiver&#x27;s text type. An <code>or</code> joins accepted types; it does not introduce a script union type. Optional callback indices appear in brackets. Signal type names describe a host-bound family.</p>',
		'<p><strong>Effects:</strong> observe reads; copy returns new values; mutate changes the receiver; advance changes a cursor or coroutine; callback may execute script; filesystem, network, output, and audio affect the host environment. Receiver text mutators return text for chaining. Core APIs exist on every engine; stdlib APIs require their registration; runner additions are provided by jaiscript.exe.</p>',
		'<h2 id="sorting-arrays">Sorting arrays</h2>',
		'<p><code>values.sort()</code> sorts the receiver in place using the language&#x27;s <code>&lt;</code>. A class&#x27;s explicit <code>operator&lt;</code> takes precedence; when absent, <code>operator&lt;=&gt;</code> supplies the comparison with zero. <code>values.sort(predicate)</code> uses a boolean predicate: true means the left item comes before the right. Equal items may be reordered. The receiver method returns no value; <code>array::sort(values[, predicate])</code> returns a sorted copy. Default numeric sorting groups all NaNs last and treats signed zeros as equivalent; an explicit predicate supplies its own ordering.</p>',
		'<div class="codeblock cb-jai"><span class="cb-label">jaiscript</span><pre><code class="lang-jai">array&lt;int&gt; values = [3, 1, 2];\nvalues.sort();\nprint(to_json(values));\nvalues.sort((a, b) =&gt; a &gt; b);\nprint(to_json(values));</code></pre></div>',
		'<div class="codeblock cb-output"><span class="cb-label">output</span><pre><code class="lang-output">[1,2,3]\n[3,2,1]</code></pre></div>',
		'<p>Typed integer, floating, boolean, byte, char, and string buffers use native sorting without per-element boxing or script comparisons when ordinary built-in ordering applies. Generic values and user comparisons use a temporary snapshot, committing the ordering after comparisons succeed. Comparison errors propagate; callback side effects are not rolled back. The predicate and element order should be a strict weak ordering that does not mutate the compared values or ordering rule; a predicate that breaks this still leaves a permutation of the elements, in an unspecified order. This is a C++-style boolean comparator, rather than JavaScript/C#&#x27;s signed comparison result.</p>',
		'<p>Builtin booleans, vectors, arrays and maps have an order. Records use their explicit &lt; or &lt;=&gt; operator; otherwise choose a predicate. For example, <code>flags.sort((a, b) =&gt; !a &amp;&amp; b)</code> orders false before true; <code>points.sort((a, b) =&gt; a.x &lt; b.x)</code> orders by x. Sorting is O(n log n); user callback cost is additional, and callback paths use O(n) temporary storage.</p>',
		'<h2 id="api-browser">Browse callable signatures</h2>',
		'<div class="api-controls"><label>Find an API <input id="api-query" type="search" placeholder="slice, sort, read_key, time, mutate..." autocomplete="off"></label><label>Provider <select id="api-provider"><option value="">All providers</option><option value="core">Core</option><option value="stdlib">Standard library</option><option value="runner">Standalone runner</option><option value="host-bound">Host-bound signals</option></select></label><p id="api-count" role="status" aria-live="polite"></p></div>',
		'<div id="api-entries">']
	owners = sorted({e['owner'] for e in entries})
	for owner in owners:
		parts.append(f'<section class="api-group"><h2 id="group-{escape(re.sub(r"[^a-z0-9]+", "-", owner.lower()).strip("-"))}">{escape(owner)}</h2>')
		for e in [item for item in entries if item['owner'] == owner]:
			identity='|'.join([e['owner'],e['provider'],e['signature']])
			anchor='api-'+hashlib.sha256(identity.encode()).hexdigest()[:12]
			provider='core' if e['provider']=='core-namespace' else e['provider']
			search=' '.join([e['display'],e['effect'],e['notes'],e['availability']]).lower()
			parts.append(f'<div class="api-entry" data-provider="{escape(provider)}" data-search="{escape(search)}"><h3 id="{anchor}"><code>{escape(e["display"])}</code></h3><p><strong>{escape(e["availability"])}</strong> &middot; {escape(e["effect"])}</p>')
			if e['notes']: parts.append('<p>'+escape(e['notes'])+'</p>')
			if e.get('example'):
				parts.append('<div class="codeblock cb-jai"><span class="cb-label">jaiscript</span><pre><code class="lang-jai">'+escape(e['example']['code'])+'</code></pre></div>')
				parts.append('<div class="codeblock cb-output"><span class="cb-label">output</span><pre><code class="lang-output">'+escape(e['example']['output'])+'</code></pre></div>')
			parts.append('</div>')
		parts.append('</section>')
	parts += ['</div>', '<h2 id="fields-constants">Fields, constants, and tokens</h2>', '<div class="tablewrap"><table><thead><tr><th>Name</th><th>Type</th><th>Access / provider</th><th>Contract</th></tr></thead><tbody>']
	for f in sorted(data['fields'],key=lambda x:(x['owner'],x['name'])):
		name=f['name'] if f['owner']=='global' else f['owner']+('::' if f['owner'] in ['string','binary','jai','math'] else '.')+f['name']
		parts.append(f'<tr><td><code>{escape(name)}</code></td><td>{escape(f["type"])}</td><td>{escape(f["access"])} / {escape(f["provider"])}</td><td>{escape(f["notes"])}</td></tr>')
	parts += ['</tbody></table></div>', '</article>']
	# Shared site chrome is generated by its existing tool after this body is emitted.
	return '<!DOCTYPE html>\n<html lang="en"><head><title>Full API signatures — JaiScript docs</title></head><body>\n<main class="content" id="main" tabindex="-1">\n'+'\n'.join(parts)+'\n</main>\n<script src="../assets/api-reference.js"></script>\n</body></html>\n'

def main():
	ap=argparse.ArgumentParser()
	ap.add_argument('--check',action='store_true')
	args=ap.parse_args()
	data=json.loads(CATALOG.read_text(encoding='utf-8'))
	assert data['entries'] and data['fields']
	outputs={SITE/'reference/api.html':marked(page(data)),PROJECT/'include/jaiscript/detail/builtin_api_arities.hpp':generated_header(data['entries'])}
	stale=[]
	for target, content in outputs.items():
		current=target.read_text(encoding='utf-8') if target.exists() else ''
		if target.suffix=='.html' and current:
			# Chrome may have been normalized; only generated main content is compared.
			current_main=re.search(r'<main\b[^>]*>([\s\S]*?)</main>',current)
			wanted_main=re.search(r'<main\b[^>]*>([\s\S]*?)</main>',content)
			crumbs=lambda body: re.sub(r'<nav class="prevnext"[\s\S]*?</nav>','',re.sub(r'^\s*<nav class="crumbs"[\s\S]*?</nav>\s*','',body))
			same=current_main and crumbs(current_main[1]).strip()==wanted_main[1].strip()
		else: same=current==content
		if not same:
			stale.append(target.relative_to(PROJECT).as_posix())
			if not args.check: target.write_text(content,encoding='utf-8',newline='\n')
	print(('Stale: '+', '.join(stale)) if args.check and stale else f'API reference: {len(data["entries"])} signatures, {len(data["fields"])} fields/constants')
	return 1 if args.check and stale else 0

if __name__=='__main__': sys.exit(main())
