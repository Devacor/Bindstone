#!/usr/bin/env python3
"""Bundle the Lua 5.4 port into one Luau program, luau/gatorquest.luau.

The luau CLI runs every required module in its own sandboxed environment, so modules cannot share globals
the way the port's do; the bundle runs each module as a function in one environment instead. Per module:
the operators Luau lacks become bit32 calls (a & b -> bit32.band(a, b), | bor, binary ~ bxor, unary ~ bnot,
<< lshift, >> rshift; // stays: Luau has floor division), and the `_G[name] = fn` export loop becomes the
function's return value, assigned to the globals by name. gq_util.lua is replaced by luau/gq_util.lua, its
hand-written twin (32-bit hash, RNG and C-division helpers on doubles). The entry point takes the program
arguments as `...` (luau gatorquest.luau -a smoke ticks N ...) and has no os.exit.

  python to_luau.py [OUTDIR]       (default: ./luau next to this script)
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from to_luajit import translate

REWRITE = {'&': 'bit32.band', '|': 'bit32.bor', '~': 'bit32.bxor', '<<': 'bit32.lshift', '>>': 'bit32.rshift'}
EXPORTS = re.compile(r'for name, fn in pairs\(\{(?P<names>.*?)\}\) do\s*_G\[name\] = fn\s*end\s*$', re.S)

def read(path):
	return open(path, encoding='utf-8').read().replace('\r\n', '\n')

def replace_once(text, old, new):
	if text.count(old) != 1:
		raise SystemExit('to_luau: expected one %r in gatorquest.lua' % old)
	return text.replace(old, new)

def module(name, src):
	m = EXPORTS.search(src)
	names = []
	if m:
		names = [pair.split('=')[0].strip() for pair in m.group('names').split(',') if pair.strip()]
		src = src[:m.start()] + 'return {' + m.group('names') + '}\n'
	elif '_G[' in src:
		raise SystemExit('to_luau: %s writes _G outside a trailing export loop' % name)
	out = ['-- ' + name + '\ndo\n\tlocal exports = (function()\n', src.rstrip('\n'), '\nend)()\n']
	for n in names:
		out.append('\t%s = exports.%s\n' % (n, n))
	out.append('end\n')
	return ''.join(out)

def main():
	out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'luau')
	entry = read(os.path.join(HERE, 'gatorquest.lua'))
	order = re.findall(r'^require\("(\w+)"\)$', entry, re.M)
	parts = ['-- GENERATED by to_luau.py from ../*.lua and gq_util.lua (one Luau program); do not edit.\n',
		'local ARGV = { ... }\n']
	for name in order:
		if name == 'gq_util':
			parts.append(module(name, read(os.path.join(out, 'gq_util.lua'))))
		else:
			parts.append(module(name, translate(read(os.path.join(HERE, name + '.lua')), REWRITE, 'bit32.bnot')))
	main_src = translate(entry, REWRITE, 'bit32.bnot')
	main_src = re.sub(r'^local dir = .*?^require\("gq_bot"\)\n', '', main_src, flags=re.S | re.M)
	main_src = replace_once(main_src, 'for i = 1, #arg do ARGS[i - 1] = arg[i] end\nlocal NARGS = #arg',
		'for i = 1, #ARGV do ARGS[i - 1] = ARGV[i] end\nlocal NARGS = #ARGV')
	main_src = replace_once(main_src, 'if arg_flag("smoke") then\n\tos.exit(run_smoke(), true)',
		'if arg_flag("smoke") then\n\treturn run_smoke()')
	main_src = replace_once(main_src, 'print("usage: lua gatorquest.lua smoke [ticks N] [seed S] [bots K] [verbose]")\nos.exit(2)',
		'error("usage: luau gatorquest.luau -a smoke [ticks N] [seed S] [bots K] [verbose]", 0)')
	parts.append('-- gatorquest\n' + main_src)
	path = os.path.join(out, 'gatorquest.luau')
	with open(path, 'w', encoding='utf-8', newline='\n') as f:
		f.write(''.join(parts))
	print('wrote', path)

if __name__ == '__main__':
	main()
