#!/usr/bin/env python3
"""Regenerate the static checker's revision from the checker's own sources.

    python tools/ci/checker_revision.py              # write include/jaiscript/detail/jaibite_checker_revision.hpp
    python tools/ci/checker_revision.py --check      # exit 1 when the committed file is not what the sources give
    python tools/ci/checker_revision.py --inputs     # the hashed files, one per line
    python tools/ci/checker_revision.py --selftest   # the hash's own checks, on throwaway copies

A .jaibite's checked-clean stamp names the revision of the checker that gave it, and a load trusts it only under the same
revision (detail/ast_serializer.hpp). The revision is the first 24 bits of a SHA-256 over the checker's translation unit:
source/implementation/type_checker.cpp and every jaiscript header it reaches through #include lines, conditional ones
too. Whatever can change the checker's object code is in it, so nobody bumps a number. Code the checker only calls into
(engine.cpp, class_registry.cpp, builtin_methods.cpp, templates.cpp, parallel_transform.cpp) is not: a rule that changes
there alone keeps the revision. The parser is k_jaibite_version's.

Each file enters as its path from the package root and its code: comments read as one space, each run of white space
outside a literal as one space, CRLF as LF. A CRLF and an LF checkout, any platform, any build of one source and a copy
whose comments were rewritten agree, and a comment edit moves nothing. Paths go in byte order. Two branches that both
change a hashed file's code conflict on the value's line; running this again on the merged sources settles it.
"""

import argparse
import hashlib
import pathlib
import re
import shutil
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
SEED = "source/implementation/type_checker.cpp"
OUTPUT = "include/jaiscript/detail/jaibite_checker_revision.hpp"
LF = b"\n"
CRLF = b"\r\n"

TEMPLATE = """#pragma once

#ifndef __JAISCRIPT_DETAIL_JAIBITE_CHECKER_REVISION_HPP__
#define __JAISCRIPT_DETAIL_JAIBITE_CHECKER_REVISION_HPP__

// Generated by tools/ci/checker_revision.py from the static checker's sources; never edited by hand, and a conflict
// here is settled by running it again.
#include <cstdint>

namespace jai::detail {
    inline constexpr uint32_t k_jaibite_checker_revision = 0x{revision:06x};
}

#endif // __JAISCRIPT_DETAIL_JAIBITE_CHECKER_REVISION_HPP__
"""

OPENER = re.compile(r'//|/\*|R"|["\']')
RAW_STRING = re.compile(r'R"([^(\s\\]*)\(')
LITERAL_BODY = {'"': re.compile(r'(?:\\[\s\S]|[^"\\\n])*'), "'": re.compile(r"(?:\\[\s\S]|[^'\\\n])*")}
SPACE = re.compile(r"\s+")
ANGLE_INCLUDE = re.compile(r"#\s*include\s*<([^>\s]+)>")
QUOTE_INCLUDE = re.compile(r"#\s*include\s*$")


def segments(text):
    """(kind, text) runs of a C++ source, kind in code, comment, literal."""
    result = []
    start = at = 0
    size = len(text)
    while True:
        opener = OPENER.search(text, at)
        if not opener:
            break
        begin = opener.start()
        token = opener.group()
        if token == "//":
            kind, end = "comment", text.find("\n", begin)
            end = size if end < 0 else end
        elif token == "/*":
            kind, end = "comment", text.find("*/", begin + 2)
            end = size if end < 0 else end + 2
        elif token == 'R"':
            raw = None if begin > 0 and (text[begin - 1].isalnum() or text[begin - 1] == "_") else RAW_STRING.match(text, begin)
            if not raw:
                at = begin + 1   # an identifier ending in R: its quote opens an ordinary literal
                continue
            kind, end = "literal", text.find(")" + raw.group(1) + '"', begin)
            end = size if end < 0 else end + len(raw.group(1)) + 2
        else:
            if token == "'" and begin > 0 and text[begin - 1].isalnum() and begin + 1 < size and text[begin + 1].isalnum():
                at = begin + 1   # a digit separator (1'000)
                continue
            kind, end = "literal", min(size, LITERAL_BODY[token].match(text, begin + 1).end() + 1)
        if begin > start:
            result.append(("code", text[start:begin]))
        result.append((kind, text[begin:end]))
        start = at = end
    if start < size:
        result.append(("code", text[start:]))
    return result


def code_of(data):
    """What a file is hashed as, and the files its #include lines name (angle names, then quoted ones)."""
    parts = []
    code = []
    angled = []
    quoted = []

    def flush():
        if code:
            run = SPACE.sub(" ", "".join(code))
            code.clear()
            angled.extend(ANGLE_INCLUDE.findall(run))
            parts.append(run)
            return bool(QUOTE_INCLUDE.search(run))
        return False

    for kind, text in segments(data.replace(CRLF, LF).decode("utf-8", errors="surrogateescape")):
        if kind == "comment":
            code.append(" ")
        elif kind == "code":
            code.append(text)
        else:
            if flush() and text.startswith('"'):
                quoted.append(text[1:-1])
            parts.append(text)
    flush()
    return "".join(parts).strip().encode("utf-8", errors="surrogateescape"), angled, quoted


def inputs(root):
    found = {}
    work = [SEED]
    while work:
        path = work.pop()
        if path in found or path == OUTPUT:
            continue
        found[path], angled, quoted = code_of((root / path).read_bytes())
        for name in angled:
            if name.startswith("jaiscript/"):
                if not (root / "include" / name).is_file():
                    raise SystemExit(f"checker_revision: {path} includes <{name}>, which is not in the package")
                work.append("include/" + name)
        for name in quoted:
            beside = (pathlib.PurePosixPath(path).parent / name).as_posix()
            if (root / beside).is_file():
                work.append(beside)
            elif (root / "include" / name).is_file():
                work.append("include/" + name)
    return dict(sorted(found.items(), key=lambda item: item[0].encode("utf-8")))


def revision_of(root):
    digest = hashlib.sha256(b"jaibite checker revision" + LF)
    for path, code in inputs(root).items():
        digest.update(path.encode("utf-8") + b"\0" + str(len(code)).encode("ascii") + b"\0" + code)
    return int.from_bytes(digest.digest()[:3], "big")


def generated(revision):
    return TEMPLATE.replace("{revision:06x}", format(revision, "06x")).encode("utf-8")


def command():
    return "python " + pathlib.Path(__file__).resolve().as_posix()


def stale(root, revision):
    """Why the committed file is not the one this revision generates; None when it is."""
    output = root / OUTPUT
    have = output.read_bytes().replace(CRLF, LF) if output.is_file() else b""
    if have == generated(revision):
        return None
    said = re.search(rb"k_jaibite_checker_revision = (0x[0-9a-fA-F]+);", have)
    return (f"the checker revision is stale: {OUTPUT} {'says ' + said.group(1).decode('ascii') if said else 'is missing or edited'}, "
            f"the checker's sources give 0x{revision:06x}. Run: {command()}")


def check(root):
    revision = revision_of(root)
    why = stale(root, revision)
    if why:
        print("::error::" + why)
        return 1
    print(f"checker revision: 0x{revision:06x}, as committed")
    return 0


def write(root):
    revision = revision_of(root)
    if not stale(root, revision):
        print(f"checker revision: 0x{revision:06x}, unchanged")
        return 0
    output = root / OUTPUT
    newline = CRLF if output.is_file() and CRLF in output.read_bytes() else LF
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(generated(revision).replace(LF, newline))
    print(f"checker revision: 0x{revision:06x}, written to {OUTPUT}")
    return 0


def selftest():
    failed = []

    def expect(what, holds):
        print(("ok: " if holds else "FAIL: ") + what)
        if not holds:
            failed.append(what)

    sample = b'int a = 1; // one\n/* two */ char c = \'"\'; auto s = "// not a comment"; auto r = R"x(/* raw */)x";\n#define M 1\'000\n'
    kinds = [(kind, text) for kind, text in segments(sample.decode("utf-8")) if kind != "code"]
    expect("comments and literals split as C++ reads them",
           kinds == [("comment", "// one"), ("comment", "/* two */"), ("literal", "'\"'"), ("literal", '"// not a comment"'), ("literal", 'R"x(/* raw */)x"')])
    expect("a file hashes as its code, literals kept whole",
           code_of(sample)[0] == b'int a = 1; char c = \'"\'; auto s = "// not a comment"; auto r = R"x(/* raw */)x"; #define M 1\'000')
    expect("its includes are read from code, not from comments or literals",
           code_of(b'#include <jaiscript/a.hpp>\n# include "b.hpp"\n// #include <jaiscript/c.hpp>\nauto t = "#include <jaiscript/d.hpp>";\n')[1:] == (["jaiscript/a.hpp"], ["b.hpp"]))

    sources = {path: (ROOT / path).read_bytes().replace(CRLF, LF) for path in inputs(ROOT)}

    def tree(base, name, newline, edit=None):
        root = pathlib.Path(base) / name
        for path, data in sources.items():
            if edit:
                data = edit(path, data)
            target = root / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data.replace(LF, newline))
        return root

    def only(wanted, edit):
        return lambda path, data: edit(data) if path == wanted else data

    base = tempfile.mkdtemp(prefix="checker_revision_selftest_")
    try:
        here = revision_of(ROOT)
        header = sorted(path for path in sources if path != SEED)[-1]
        expect("the same tree gives the same value twice", here == revision_of(ROOT))
        lf = tree(base, "lf", LF)
        expect("an LF copy of the inputs gives the checkout's value", revision_of(lf) == here)
        expect("a CRLF copy of the inputs gives the checkout's value", revision_of(tree(base, "crlf", CRLF)) == here)
        expect("a copy holds only the inputs, so nothing else is read", sorted(inputs(lf)) == sorted(sources))
        expect("the checker and its header are hashed, the generated file is not",
               SEED in sources and "include/jaiscript/detail/type_checker.hpp" in sources and OUTPUT not in sources)
        expect("a comment and blank lines added to type_checker.cpp keep the value",
               revision_of(tree(base, "commented", LF, only(SEED, lambda data: b"// a note\n\n" + data.replace(LF, b"   // more\n", 1) + b"\n/* the end */\n"))) == here)
        expect("one declaration added to type_checker.cpp gives another value",
               revision_of(tree(base, "declared", LF, only(SEED, lambda data: data + b"static int checker_revision_selftest;\n"))) != here)
        expect("one character changed in a literal of type_checker.cpp gives another value",
               revision_of(tree(base, "literal", LF, only(SEED, lambda data: data + b'static const char* checker_revision_selftest = "a  b";\n'))) !=
               revision_of(tree(base, "spaced", LF, only(SEED, lambda data: data + b'static const char* checker_revision_selftest = "a b";\n'))))
        expect(f"one declaration added to a header it reaches ({header}) gives another value",
               revision_of(tree(base, "reached", LF, only(header, lambda data: data + b"static int checker_revision_selftest;\n"))) != here)
        write(lf)
        expect("a written value passes --check", stale(lf, here) is None)
        (lf / OUTPUT).write_bytes(generated(here ^ 1))
        expect("another value fails --check and names the command", command() in (stale(lf, here) or ""))
        (lf / OUTPUT).write_bytes(generated(here ^ 1).replace(LF, CRLF))
        write(lf)
        expect("a rewrite keeps the file's line endings", CRLF in (lf / OUTPUT).read_bytes() and stale(lf, here) is None)
    finally:
        shutil.rmtree(base, ignore_errors=True)
    print("SELFTEST RED" if failed else "SELFTEST GREEN")
    return 1 if failed else 0


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--inputs", action="store_true")
    parser.add_argument("--selftest", action="store_true")
    arguments = parser.parse_args()
    if arguments.selftest:
        return selftest()
    if arguments.inputs:
        print("\n".join(inputs(ROOT)))
        return 0
    return check(ROOT) if arguments.check else write(ROOT)


if __name__ == "__main__":
    sys.exit(main())
