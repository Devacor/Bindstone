def indent(text, levels=1):
    pad = "\t" * levels
    return "\n".join((pad + line) if line.strip() else line for line in text.strip("\n").split("\n")) + "\n"

def fields(*decls):
    return "".join("\t" + d + "\n" for d in decls) + ("\n" if decls else "")

def method(signature, body):
    return "\t" + signature + " {\n" + indent(body, 2) + "\t}\n\n"

def spawn(body): return method("void spawn() override", body) if body.strip() else ""
def death(body): return method("void death() override", body) if body.strip() else ""
def tick(body): return method("bool tick(double dt) override", body.rstrip("\n") + "\n\treturn false;") if body.strip() else ""

def melee(damage, on_hit=""):
    body = "if (game().creature(target) == null || !game().creature(target).alive()) {\n\treturn;\n}\n"
    if on_hit:
        body += on_hit.strip("\n") + "\n"
    body += f"strike(target, {damage});"
    return method("void attackTarget(var& targeting, int target) override", body)

def missile(damage, prelude=""):
    body = (prelude.strip("\n") + "\n" if prelude else "") + f"fireMissile(target, {damage});"
    return method("void attackTarget(var& targeting, int target) override", body)

